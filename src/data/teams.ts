export function getTeamById(id: string, customTeams: TeamPreset[] = []): TeamPreset | undefined {
  return customTeams.find((t) => t.id === id) || TEAMS.find((t) => t.id === id)
}

/**
 * Creates formation on-pitch players and bench players for a team preset.
 */
export function createTeamPlayers(
  team: TeamPreset,
  teamSide: TeamId,
  formation: FormationId = team.formation,
): { starters: Player[]; bench: BenchPlayer[] } {
  const slots = createFormationPlayers(formation, teamSide)
  const starters: Player[] = slots.map((slot, i) => {
    const presetPlayer = team.startingXI[i]
    return {
      ...slot,
      number: presetPlayer ? presetPlayer.number : slot.number,
      name: presetPlayer ? presetPlayer.name : slot.name,
      role: presetPlayer ? presetPlayer.role : slot.name,
    }
  })

  const bench: BenchPlayer[] = team.bench.map((bp, i) => ({
    id: `${teamSide}-bench-${i}-${Date.now().toString(36)}`,
    team: teamSide,
    number: bp.number,
    name: bp.name,
    role: bp.role,
  }))

  return { starters, bench }
}
